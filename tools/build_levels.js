// Bucket solver results into difficulty pools. r[m] = solver nodes to win with m redeals (-1 = not found).
const fs = require('fs'), out = {};
for (const d of [1, 3]) {
  const rows = JSON.parse(fs.readFileSync('pool' + d + '.json'));
  const ok = (x, m) => x.r[m] >= 0;
  const P = { beginner: [], easy: [], medium: [], hard: [], expert: [], grandmaster: [] };
  for (const x of rows) {
    if (ok(x, 0)) P.grandmaster.push(x.s);                                       // wins in a single pass
    if (ok(x, 1) && (!ok(x, 0) || x.b >= 9)) P.expert.push(x.s);                 // needs the one redeal, or deeply buried
    if (ok(x, 3) && !ok(x, 0) && x.r[3] > 300) P.hard.push(x.s);                 // wins only with redeals, solver had to search
    if (ok(x, 3) && x.b >= 5) P.medium.push(x.s);
    if (ok(x, 99) && x.r[99] < 3000) P.easy.push(x.s);
    if (ok(x, 99) && x.r[99] < 600 && x.b <= 7) P.beginner.push(x.s);          // quick to solve, aces/kings near the surface
  }
  // never leave a level empty: fall back to the next easier verified pool
  const order = ['beginner', 'easy', 'medium', 'hard', 'expert', 'grandmaster'];
  for (let i = 0; i < order.length; i++) if (P[order[i]].length < 20) P[order[i]] = P[order[i]].concat(P[order[Math.max(0, i - 1)]]).slice(0, 400);
  out[d] = P; console.log('draw', d, Object.entries(P).map(([k, v]) => k + ':' + v.length).join(' '));
}
fs.writeFileSync('../levels.js', '/* Verified-winnable deal pools per difficulty and draw mode (generated by tools/build_levels.js). */\nwindow.LEVEL_POOLS = ' + JSON.stringify(out) + ';\n');
